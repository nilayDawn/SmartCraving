    http_req_duration: ['p(95)<1500', 'p(99)<2500'], // Global latency SLAs

    // Granular Per-Endpoint SLAs
    'http_req_duration{endpoint:stripe_api}': ['p(95)<300'],         // In-memory publishable key retrieval
