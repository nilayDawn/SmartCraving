/**
 * Setup lifecycle hook:
 * 1. Verifies backend connectivity
 * 2. Discovers an active restaurant and food item for the controlled checkout iteration
 */
export function setup() {
  const healthRes = http.get(ENDPOINTS.HEALTH, {
    tags: { name: 'GET /health (pre-check)' },
  });

  if (healthRes.status !== 200) {
    console.warn(`[Setup Warning] Health check at ${ENDPOINTS.HEALTH} returned ${healthRes.status}. Verify backend is running.`);
  }

  let storeId = env.TEST_STORE_ID || null;
  let foodItemId = env.TEST_FOOD_ID || null;

  // Discover valid store
  if (!storeId) {
    const storesRes = http.get(`${ENDPOINTS.EATS}/stores`, {
      headers: jsonHeaders,
      tags: { name: 'GET /api/v1/eats/stores (setup discovery)' },
    });

    if (storesRes.status === 200) {
      try {
        const body = storesRes.json();
        const list = body.restaurants || (body.data && body.data.restaurants) || [];
        if (list.length > 0 && list[0]._id) {
          storeId = list[0]._id;
        }
      } catch (_) {}
    }
  }

  if (!storeId) {
    storeId = FALLBACK_STORE_ID;
  }

  // Discover valid food item
  if (!foodItemId) {
    const itemsRes = http.get(`${ENDPOINTS.EATS}/items/${storeId}`, {
      headers: jsonHeaders,
      tags: { name: 'GET /api/v1/eats/items/:storeId (setup discovery)' },
    });

    if (itemsRes.status === 200) {
      try {
        const body = itemsRes.json();
        const list = Array.isArray(body.data) ? body.data : (body.foodItems || []);
        if (list.length > 0 && list[0]._id) {
          foodItemId = list[0]._id;
        }
      } catch (_) {}
    }
  }

  if (!foodItemId) {
    foodItemId = FALLBACK_FOOD_ID;
  }

  return {
    targetUrl: BASE_URL,
    storeId,
    foodItemId,
  };
}

// Module-level state per Virtual User (persists across iterations of each VU)
let vuToken = null;
let vuUser = null;

/**
 * Ensures the Virtual User has an active, authenticated customer account.
 * Reuses credentials across iterations to avoid repeated bcrypt password hashing.
 */
function ensureAuthenticatedUser(vuId, extraHeaders) {
  if (vuToken) return { token: vuToken, user: vuUser };

  const email = `pay_user_vu${vuId}_${Date.now()}@loadtest.local`;
  const password = 'Password123!';
  const phoneSuffix = Math.floor(10000000 + Math.random() * 90000000);
  const phoneNumber = `98${phoneSuffix}`.slice(0, 10);

  const signupRes = http.post(
    `${ENDPOINTS.USERS}/signup`,
    JSON.stringify({
      name: `Pay User ${vuId}`,
      email,
      password,
      passwordConfirm: password,
      phoneNumber,
    }),
    {
      headers: { ...jsonHeaders, ...extraHeaders },
      tags: { name: 'POST /api/v1/users/signup (payment auth)', endpoint: 'auth' },
    },
  );

  if (signupRes.status === 200) {
    try {
      const data = signupRes.json();
      vuToken = data.token;
      vuUser = data.data && data.data.user ? data.data.user : null;
    } catch (_) {}
  }

  // Fallback to configured standard test user login if signup failed
  if (!vuToken && env.TEST_USER_EMAIL && env.TEST_USER_PASSWORD) {
    const loginRes = http.post(
      `${ENDPOINTS.USERS}/login`,
      JSON.stringify({
        email: env.TEST_USER_EMAIL,
        password: env.TEST_USER_PASSWORD,
      }),
      {
        headers: { ...jsonHeaders, ...extraHeaders },
        tags: { name: 'POST /api/v1/users/login (payment auth fallback)', endpoint: 'auth' },
      },
    );

    if (loginRes.status === 200) {
      try {
        const data = loginRes.json();
        vuToken = data.token;
        vuUser = data.data && data.data.user ? data.data.user : null;
      } catch (_) {}
    }
  }

  return { token: vuToken, user: vuUser };
}

/**
 * Scenario A: Read-Only Stripe API Key Load Test (Executed under higher staged load)
 * Endpoint tested:
 *   GET /api/v1/stripeapi
 */
export function readStripeApiScenario() {
  // Distributed IP simulation to avoid rate limiter bottlenecks
  const clientIp = `10.${(__VU % 250) + 1}.${((__ITER || 0) % 250) + 1}.1`;
  const extraHeaders = {
    'X-Forwarded-For': clientIp,
  };

  // 1. Authenticate customer
  const { token } = ensureAuthenticatedUser(__VU, extraHeaders);
  if (!token) {
    console.error(`[VU ${__VU}] Failed to authenticate payment customer.`);
    sleep(1);
    return;
  }

  const authHeaders = getAuthHeaders(token, extraHeaders);

  // =========================================================================
  // 2. GET /api/v1/stripeapi
  // =========================================================================
  const stripeRes = http.get(
    `${ENDPOINTS.PAYMENTS}/stripeapi`,
    {
      headers: authHeaders,
      tags: { name: 'GET /api/v1/stripeapi', endpoint: 'stripe_api' },
    },
  );

  check(stripeRes, {
    'stripeapi status is 200': (r) => r.status === 200,
    'stripeapi returns publishable key': (r) => {
      try {
        const body = r.json();
        return body && typeof body.stripeApiKey === 'string' && body.stripeApiKey.length > 10;
      } catch (_) {
        return false;
      }
    },
    'stripeapi is configured with Stripe Test key': (r) => {
      try {
        const key = r.json('stripeApiKey');
        return typeof key === 'string' && key.startsWith('pk_test_');
      } catch (_) {
        return false;
      }
    },
  });

  // Short pause between reads
  sleep(0.5);
}

/**
 * Scenario B: Controlled Payment Process Test
 * Endpoint tested:
 *   POST /api/v1/payment/process
 *
 * Safety Guarantees:
 *   - Runs with small controlled iterations (1 VU, 1-2 iterations).
 *   - Validates empty-cart error handling without calling external Stripe APIs.
 *   - Verifies real checkout session creation against Stripe's Test environment.
 *   - Does NOT submit credit card credentials or execute financial transactions.
 *   - Automatically cleans up the cart item after checkout URL verification.
 */
export function controlledPaymentScenario(data) {
  const storeId = data.storeId || FALLBACK_STORE_ID;
  const foodItemId = data.foodItemId || FALLBACK_FOOD_ID;

  // Use dedicated IP for controlled payment processing
  const clientIp = `10.201.${(__VU % 50) + 1}.${((__ITER || 0) % 50) + 1}.1`;
  const extraHeaders = {
    'X-Forwarded-For': clientIp,
  };

  const { token } = ensureAuthenticatedUser(998, extraHeaders);
  if (!token) {
    console.error('[Controlled Payment Process] Authentication failed.');
    sleep(1);
    return;
  }

  const authHeaders = getAuthHeaders(token, extraHeaders);

  // =========================================================================
  // Step 1: POST /api/v1/payment/process with EMPTY Cart (Validation Guard)
  // Verifies authentication, rate limiter, and empty cart business validation
  // without making external Stripe API calls
  // =========================================================================
  const emptyRes = http.post(
    `${ENDPOINTS.PAYMENTS}/payment/process`,
    JSON.stringify({}),
    {
      headers: authHeaders,
      tags: { name: 'POST /api/v1/payment/process (empty cart validation)', endpoint: 'payment_process' },
      responseCallback: http.expectedStatuses(400),
    },
  );

  check(emptyRes, {
    'empty cart status is 400': (r) => r.status === 400,
    'empty cart message is "Your cart is empty"': (r) => {
      try {
        const msg = r.json('message') || r.json('errMessage');
        return msg === 'Your cart is empty';
      } catch (_) {
        return false;
      }
    },
    'empty cart avoided 500 error': (r) => r.status !== 500,
  });

  sleep(1);

  // =========================================================================
  // Step 2: Controlled Stripe Test Checkout Session Generation
  // 1. Add valid item to cart
  // 2. Call POST /api/v1/payment/process to create Stripe Test Checkout Session
  // 3. Verify returned checkout URL
  // 4. Remove item from cart to maintain clean state
  // =========================================================================
  const addRes = http.post(
    `${ENDPOINTS.CART}/add-to-cart`,
    JSON.stringify({
      restaurantId: storeId,
      foodItemId: foodItemId,
      quantity: 1,
    }),
    {
      headers: authHeaders,
      tags: { name: 'POST /api/v1/eats/cart/add-to-cart (payment prep)', endpoint: 'cart' },
    },
  );

  if (addRes.status === 200) {
    // Call POST /payment/process to create Checkout Session
    const processRes = http.post(
      `${ENDPOINTS.PAYMENTS}/payment/process`,
      JSON.stringify({}),
      {
        headers: authHeaders,
        tags: { name: 'POST /api/v1/payment/process (session creation)', endpoint: 'payment_process' },
        responseCallback: http.expectedStatuses(200),
      },
    );

    check(processRes, {
      'payment process status is 200': (r) => r.status === 200,
      'payment process returned checkout url': (r) => {
        try {
          const body = r.json();
          return body && typeof body.url === 'string' && body.url.startsWith('https://checkout.stripe.com/');
        } catch (_) {
          return false;
        }
      },
      'payment process within rate limits (not 429)': (r) => r.status !== 429,
    });

    // Cleanup: Remove item from cart
    http.del(
      `${ENDPOINTS.CART}/delete-cart-item`,
      JSON.stringify({ foodItemId }),
      {
        headers: authHeaders,
        tags: { name: 'DELETE /api/v1/eats/cart/delete-cart-item (cleanup)', endpoint: 'cart' },
      },
    );
  }

  sleep(1);
}

/**
 * Resolves destination path for payments.json depending on execution directory
 */
function getSummaryFilePath() {
  if (env.SUMMARY_PATH) return env.SUMMARY_PATH;
  const pwd = env.PWD || '';
  if (pwd.endsWith('Load-tests') || pwd.endsWith('Load-tests/')) {
    return 'results/payments.json';
  }
  return 'Load-tests/results/payments.json';
}

/**
 * Custom readable terminal summary formatter
 */
function formatTerminalSummary(data, summaryPath) {
  const m = data.metrics;
  const httpReqs = m.http_reqs ? m.http_reqs.values.count : 0;
  const httpFailed = m.http_req_failed ? (m.http_req_failed.values.rate * 100).toFixed(2) : '0.00';
  const duration = m.http_req_duration ? m.http_req_duration.values : {};
  const checks = m.checks ? m.checks.values : { passes: 0, fails: 0 };
  const totalChecks = checks.passes + checks.fails;
  const checkRate = totalChecks > 0 ? ((checks.passes / totalChecks) * 100).toFixed(2) : '100.00';

  let out = '\n' + '='.repeat(70) + '\n';
  out += '         SMARTCRAVING - PAYMENTS LOAD TEST RESULTS (SCENARIOS A & B)     \n';
  out += '='.repeat(70) + '\n\n';

  out += `  Target API URL     : ${BASE_URL}\n`;
  out += '  Stripe Environment : TEST / SANDBOX MODE (sk_test_... / pk_test_...)\n';
  out += `  Total HTTP Reqs    : ${httpReqs}\n`;
  out += `  Check Pass Rate    : ${checkRate}% (${checks.passes}/${totalChecks} checks passed)\n`;
  out += `  Failure Rate       : ${httpFailed}%\n\n`;

  out += '  Latency Overview (ms):\n';
  out += `    Average          : ${duration.avg ? duration.avg.toFixed(2) : '-'} ms\n`;
  out += `    Median (p50)     : ${duration.med ? duration.med.toFixed(2) : '-'} ms\n`;
  out += `    90th Percentile  : ${duration['p(90)'] ? duration['p(90)'].toFixed(2) : '-'} ms\n`;
  out += `    95th Percentile  : ${duration['p(95)'] ? duration['p(95)'].toFixed(2) : '-'} ms\n`;
  out += `    99th Percentile  : ${duration['p(99)'] ? duration['p(99)'].toFixed(2) : '-'} ms\n`;
  out += `    Maximum          : ${duration.max ? duration.max.toFixed(2) : '-'} ms\n\n`;

  out += '  Per-Endpoint p(95) Latency:\n';
  const endpoints = [
    { key: 'stripe_api', label: 'GET /stripeapi' },
    { key: 'payment_process', label: 'POST /payment/process' },
  ];

  for (const ep of endpoints) {
    const metricKey = `http_req_duration{endpoint:${ep.key}}`;
    const epMetric = m[metricKey];
    const epP95 = epMetric && epMetric.values ? epMetric.values['p(95)'].toFixed(2) + ' ms' : 'N/A';
    out += `    - ${ep.label.padEnd(28)} : p(95) = ${epP95}\n`;
  }

  out += '\n  Threshold Evaluation:\n';
  let allPassed = true;
  for (const [key, metric] of Object.entries(m)) {
    if (metric.thresholds) {
      for (const [tName, tResult] of Object.entries(metric.thresholds)) {
        const passed = tResult.ok;
        if (!passed) allPassed = false;
        const icon = passed ? '✓ PASS' : '✗ FAIL';
        out += `    [${icon}] ${key} (${tName})\n`;
      }
    }
  }
  if (allPassed) {
    out += '    ✓ All payment SLA performance thresholds were satisfied.\n';
  }

  out += `\n  Summary JSON saved to : ${summaryPath}\n`;
  out += '='.repeat(70) + '\n';
  return out;
}

/**
 * k6 handleSummary hook: formats terminal output and writes JSON summary to payments.json
 */
export function handleSummary(data) {
  const summaryPath = getSummaryFilePath();
  return {
    stdout: formatTerminalSummary(data, summaryPath),
    [summaryPath]: JSON.stringify(data, null, 2),
  };
}
